def _vector_key(vector: Sequence[float]) -> Vector:
    """Normalise les coordonnées pour neutraliser les écarts flottants."""
    if len(vector) != 3:
        raise ValueError(f"Un vecteur doit avoir 3 coordonnées : {vector}")
    return tuple(round(float(value), 12) for value in vector)


def list_to_positions(
    groups: Sequence[Group],
    reference: Sequence[Sequence[float]],
) -> list[list[int]]:
    """Remplace chaque vecteur par son indice dans la liste de référence."""
    index_map: dict[Vector, int] = {}

    for index, vector in enumerate(reference):
        key = _vector_key(vector)
        if key in index_map:
            raise ValueError(
                f"Deux directions identiques après normalisation : {vector}"
            )
        index_map[key] = index

    positions: list[list[int]] = []
    for group in groups:
        group_positions: list[int] = []
        for vector in group:
            key = _vector_key(vector)
            if key not in index_map:
                raise ValueError(
                    f"Direction absente de la liste de référence : {vector}"
                )
            group_positions.append(index_map[key])
        positions.append(group_positions)

    return positions


def get_constraint_positions() -> tuple[list[list[int]], list[list[int]]]:
    """Retourne les triplets et paires sous forme d'indices."""
    return (
        list_to_positions(triplets, directions_peres),
        list_to_positions(pairs, directions_peres),
    )
